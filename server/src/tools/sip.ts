export interface SipInput {
  provider: string;
  format: string;
  name: string;
  username: string;
  password: string;
  host?: string;
  port?: number;
  transport?: string;
  context?: string;
  codecs?: string;
  fromDomain?: string;
}

const TOKEN = /^[A-Za-z0-9_.-]{1,64}$/;
const HOST = /^[A-Za-z0-9_.:-]{1,253}$/;

function token(value: string, label: string): string {
  const text = value.trim();
  if (!TOKEN.test(text)) {
    throw new Error(`${label} must be 1-64 letters, digits, dots, underscores, or hyphens`);
  }
  return text;
}

function secret(value: string): string {
  if (value.length < 8 || value.length > 128) throw new Error("Password must be 8-128 characters");
  for (let i = 0; i < value.length; i += 1) {
    const code = value.charCodeAt(i);
    if (code < 32 || code === 127) throw new Error("Password cannot contain a line break");
  }
  return value;
}

export function renderSip(input: SipInput): { filename: string; text: string; note: string } {
  const preset = PROVIDERS.find((row) => row.id === input.provider);
  if (!preset) throw new Error("Unknown provider");
  const format: SipFormat = input.format === "chan_sip" ? "chan_sip" : input.format === "pjsip" ? "pjsip" : (() => { throw new Error("Format must be pjsip or chan_sip"); })();
  const name = token(input.name, "Trunk name");
  const username = token(input.username, "Username");
  const password = secret(input.password);
  const host = (input.host?.trim() || preset.host).trim();
  if (!host || !HOST.test(host)) throw new Error("Host must be a hostname or IP address");
  const port = input.port ?? preset.port;
  if (!Number.isInteger(port) || port < 1 || port > 65535) throw new Error("Port is out of range");
  const transport = input.transport === "tcp" || input.transport === "tls" || input.transport === "udp" ? input.transport : preset.transport;
  const context = token(input.context?.trim() || "from-trunk", "Context");
  const codecs = (input.codecs?.trim() || preset.codecs.join(","))
    .split(",")
    .map((item) => item.trim())
    .filter(Boolean);
  if (codecs.length === 0 || codecs.some((codec) => !TOKEN.test(codec))) {
    throw new Error("Codecs must be a comma-separated list of names such as ulaw,alaw");
  }
  const fromDomain = input.fromDomain?.trim() || host;
  if (!HOST.test(fromDomain)) throw new Error("From domain must be a hostname or IP address");

  const header = [
    `; Generated by Span for ${preset.label}.`,
    "; Review it, then paste it into the matching custom file. Span does not write to the PBX.",
    `; ${preset.note}`,
    "",
  ];

  if (format === "chan_sip") {
    return {
      filename: "sip_custom.conf",
      note: preset.note,
      text: [
        ...header,
        `[${name}]`,
        "type=peer",
        `host=${host}`,
        `port=${port}`,
        `defaultuser=${username}`,
        `remotesecret=${password}`,
        `fromdomain=${fromDomain}`,
        `context=${context}`,
        "insecure=port,invite",
        `disallow=all`,
        ...codecs.map((codec) => `allow=${codec}`),
        `transport=${transport}`,
        "directmedia=no",
        "nat=force_rport,comedia",
        "qualify=yes",
        "sendrpid=pai",
        "",
      ].join("\n"),
    };
  }

  const allow = codecs.join(",");
  return {
    filename: "pjsip_custom.conf",
    note: preset.note,
    text: [
      ...header,
      `[${name}]`,
      "type=endpoint",
      `context=${context}`,
      "disallow=all",
      `allow=${allow}`,
      `outbound_auth=${name}-auth`,
      `aors=${name}`,
      "direct_media=no",
      "rtp_symmetric=yes",
      "force_rport=yes",
      "rewrite_contact=yes",
      "send_pai=yes",
      ...(fromDomain !== host ? [`from_domain=${fromDomain}`] : []),
      "",
      `[${name}]`,
      "type=aor",
      "max_contacts=1",
      `contact=sip:${host}:${port}`,
      "qualify_frequency=60",
      "",
      `[${name}-auth]`,
      "type=auth",
      "auth_type=userpass",
      `username=${username}`,
      `password=${password}`,
      "",
      `[${name}-reg]`,
      "type=registration",
      `outbound_auth=${name}-auth`,
      `server_uri=sip:${host}:${port}`,
      `client_uri=sip:${username}@${host}`,
      "retry_interval=60",
      "",
      `[${name}-identify]`,
      "type=identify",
      `endpoint=${name}`,
      `match=${host}`,
      "",
    ].join("\n"),
  };
}
