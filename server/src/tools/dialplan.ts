export interface DialplanInput {
  did: string;
  extension: string;
  outboundPrefix: string;
  strip: number;
  trunk: string;
  callerId?: string;
}

const DIGITS = /^\d{2,16}$/;
const PREFIX = /^\d{1,16}$/;
const NAME = /^[A-Za-z0-9_.-]{1,64}$/;

export function renderDialplan(input: DialplanInput): string {
  if (!DIGITS.test(input.did)) throw new Error("DID must be 2-16 digits");
  if (!DIGITS.test(input.extension)) throw new Error("Extension must be 2-16 digits");
  if (!PREFIX.test(input.outboundPrefix)) throw new Error("Outbound prefix must be 1-16 digits");
  if (!Number.isInteger(input.strip) || input.strip < 0 || input.strip > 8) {
    throw new Error("Strip must be a whole number from 0 to 8");
  }
  if (!NAME.test(input.trunk)) throw new Error("Trunk name must be 1-64 letters, digits, dots, underscores, or hyphens");
  const callerId = (input.callerId ?? "").trim();
  if (callerId && !/^[\d+]{2,20}$/.test(callerId)) throw new Error("Caller ID must be digits, with an optional leading +");
  const dial = input.strip > 0 ? `\${EXTEN:${input.strip}}` : "${EXTEN}";
  const cid = callerId
    ? [` same => n,Set(CALLERID(num)=${callerId.replace(/^\+/, "")})`]
    : [];
  return [
    "; Generated by Span. Paste into extensions_custom.conf, then dialplan reload.",
    "; This does not replace the FreePBX GUI routes. It is a starting point for a custom context.",
    "",
    "[from-pstn-custom]",
    `exten => ${input.did},1,NoOp(Inbound DID \${EXTEN})`,
    " same => n,Answer()",
    ` same => n,Goto(from-internal,${input.extension},1)`,
    "",
    "[from-internal-custom]",
    `exten => _${input.outboundPrefix}.,1,NoOp(Outbound via ${input.trunk})`,
    ...cid,
    ` same => n,Dial(PJSIP/${dial}@${input.trunk},60)`,
    " same => n,Hangup()",
    "",
  ].join("\n");
}
